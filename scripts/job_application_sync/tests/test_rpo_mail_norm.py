"""RPOアドレス補完の会社名突合キーの回帰テスト (2026-08-10)。

## なぜ直したか

取引名は会社名と拠点名を全角アンダースコアで繋ぐ:
    「株式会社不二家＿平塚工場」
一方、顧客管理シートは区切り無しで書く:
    「株式会社不二家平塚工場」

旧実装は `＿` を `_` に**変換**していたため、両者は永久に一致しなかった。

実測 (2026-08-10):
    管理用メールが空の納品管理PL取引 1,805件のうち
      `_` を残す → シートに当たる  875件
      `_` を消す → シートに当たる  936件  (+61)
    補完できる取引: 4件 → **46件**
    `_` 削除でシート側のキーが衝突する件数: **0件** (別会社を掴む恐れなし)

この鍵が空だと sync_deal_association が求人を取引に紐付けられず、
応募側の一次対応の要否・担当者・取引名が空のままになる。
実測: 直近14日の応募1,206件のうち228件(19%)がこの経路で欠けていた。

## 守る不変条件

1. 区切り記号(＿ / _ / 全角空白 / 半角空白)の有無を吸収する
2. **拠点名そのものは落とさない**（落とすと別拠点・別会社を掴む。
   実測で「ジャパンクリエイト北上営業所」に出雲中央交通のアドレスが
   当たった例がある）
3. 全角/半角・大文字小文字・括弧の有無を吸収する
"""
from __future__ import annotations

import pytest

from scripts.job_application_sync.backfill_deal_rpo_mail import norm


# --------------------------------------------------------------------------
# 1. 区切り記号の有無を吸収する（今回の修正点）
# --------------------------------------------------------------------------
@pytest.mark.parametrize("deal,sheet", [
    ("株式会社不二家＿平塚工場", "株式会社不二家平塚工場"),
    ("日本製紙リキッドパッケージプロダクト株式会社＿江川事業所",
     "日本製紙リキッドパッケージプロダクト株式会社　江川事業所"),
    ("株式会社ＹＡＭＡＮＡＫＡ＿高崎工場", "株式会社ＹＡＭＡＮＡＫＡ高崎工場"),
    ("株式会社つばめ急便＿西宮センター", "株式会社つばめ急便 西宮センター"),
    ("株式会社上組＿箕沖支店", "株式会社上組箕沖支店"),
])
def test_区切りの有無を吸収して一致する(deal, sheet):
    assert norm(deal) == norm(sheet)


def test_半角アンダースコアも消す():
    assert norm("A社_東京営業所") == norm("A社東京営業所")


# --------------------------------------------------------------------------
# 2. 拠点名は落とさない（別拠点を掴まないための最重要条件）
# --------------------------------------------------------------------------
def test_拠点が違えば一致しない():
    assert norm("株式会社不二家＿平塚工場") != norm("株式会社不二家＿泉佐野工場")


def test_拠点の有無で一致しない():
    """シートに拠点が無い場合は当てない（どの拠点か決められないため）。"""
    assert norm("マキタ運輸株式会社") != norm("株式会社マキタ運輸＿福岡営業所")


def test_別会社は一致しない():
    assert norm("ジャパンクリエイト＿北上営業所") != norm("出雲中央交通株式会社")


# --------------------------------------------------------------------------
# 3. 表記ゆれの吸収（従来からの挙動を壊さない）
# --------------------------------------------------------------------------
@pytest.mark.parametrize("a,b", [
    ("株式会社ＹＡＭＡＮＡＫＡ", "株式会社YAMANAKA"),      # 全角/半角
    ("A社 東京", "A社　東京"),                           # 半角/全角スペース
    ("A社（東京）", "A社東京"),                          # 括弧は外して中身を残す
    ("ABC商事", "abc商事"),                             # 大文字小文字
])
def test_表記ゆれを吸収する(a, b):
    assert norm(a) == norm(b)


def test_括弧の中身は落とさない():
    """括弧を外すだけで中身は残す。落とすと拠点情報が消える。"""
    assert norm("A社（東京営業所）") == norm("A社東京営業所")
    assert norm("A社（東京営業所）") != norm("A社")


def test_空文字とNoneで落ちない():
    assert norm("") == ""
    assert norm(None) == ""
